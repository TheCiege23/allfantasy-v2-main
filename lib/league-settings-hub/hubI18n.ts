/**
 * Stat names that collide with the UI's own words. "Save" is the button verb everywhere else in
 * the hub, so the STAT "Save" is only ever looked up here — through `{ stat: true }` — and never
 * reaches a button. (Found on a soccer league whose Save button read "Atajada".)
 */
const STAT_ES: Record<string, string> = { Save: 'Atajada' }
const STAT_ES_BY_FAMILY: Partial<Record<SportFamily, Record<string, string>>> = {
  baseball: { Save: 'Salvamento' },
}

const MONTHS_ES: Record<string, string> = {
  Jan: 'ene', Feb: 'feb', Mar: 'mar', Apr: 'abr', May: 'may', Jun: 'jun',
  Jul: 'jul', Aug: 'ago', Sep: 'sept', Oct: 'oct', Nov: 'nov', Dec: 'dic',
}

const UNIT_ES: Record<string, [string, string]> = {
  day: ['día', 'días'], hour: ['hora', 'horas'], minute: ['minuto', 'minutos'], second: ['segundo', 'segundos'],
  round: ['ronda', 'rondas'], team: ['equipo', 'equipos'],
}

type Tr = (s: string) => string

/** Strings with a number or a name in them. Each replacer receives the translator for its parts. */
const PATTERNS: Array<[RegExp, (m: RegExpExecArray, tr: Tr) => string]> = [
  [/^(\d+) (day|hour|minute|second|round|team)s?$/i, (m) => {
    const n = Number(m[1])
    const [one, many] = UNIT_ES[m[2]!.toLowerCase()]!
    return `${n} ${n === 1 ? one : many}`
  }],
  [/^(\d+) sec$/, (m) => `${m[1]} s`],
  [/^Week (\d+)$/, (m) => `Semana ${m[1]}`],
  [/^(\d+) per team$/, (m) => `${m[1]} por equipo`],
  [/^Team (\d+)$/, (m) => `Equipo ${m[1]}`],
  [/^(\d{4}) Season$/, (m) => `Temporada ${m[1]}`],
  [/^(\d{4}) (Rookie Draft|Season Draft)$/, (m, tr) => `${tr(m[2]!)} ${m[1]}`],
  [/^Shown in (.+)$/, (m) => `Mostrado en ${m[1]}`],
  [/^Time shown in league time$/, () => 'Hora mostrada en la hora de la liga'],
  [/^Time shown in (.+)$/, (m) => `Hora mostrada en ${m[1]}`],
  [/^1 point every (\d+) yards$/, (m) => `1 punto cada ${m[1]} yardas`],
  [/^Imported from (.+)$/, (m) => `Importada de ${m[1]}`],
  [/^These rules mirror your host league\. Change them on (.+) and they sync here\.$/, (m) => `Estas reglas copian tu liga de origen. Cámbialas en ${m[1]} y se sincronizan aquí.`],
  [/^Co-owners are managed on (.+)\.$/, (m) => `Los copropietarios se gestionan en ${m[1]}.`],
  [/^Invitation sent to (.+)$/, (m) => `Invitación enviada a ${m[1]}`],
  [/^Co-commissioner: (.+)$/, (m) => `Cocomisionado: ${m[1]}`],
  [/^Runner-up (.+)$/, (m) => `Subcampeón ${m[1]}`],
  [/^(.+) Updates$/, (m, tr) => `Novedades de ${tr(m[1]!)}`],
  [/^(.+) seasons$/, (m) => `temporadas ${m[1]}`],
  [/^Show all (\d+)$/, (m) => `Mostrar los ${m[1]}`],
  [/^Request failed \((\d+)\)$/, (m) => `La solicitud falló (${m[1]})`],
  // Stat names that carry a range.
  [/^FG Miss (.+)$/, (m) => `FG fallado ${m[1]}`],
  [/^PA: (.+)$/, (m) => `Puntos permitidos: ${m[1]}`],
  [/^Points allowed (.+)$/, (m) => `Puntos permitidos ${m[1]}`],
  // The legend's matchup lines (sportProfile `matchup`).
  [/^A weak (defense|pitching staff)\. Your player is more likely to beat their projection\.$/, (m) => `${m[1] === 'defense' ? 'Una defensa débil' : 'Un cuerpo de lanzadores débil'}. Es más probable que tu jugador supere su proyección.`],
  [/^An average (defense|pitching staff)\. Expect close to the projection\.$/, (m) => `${m[1] === 'defense' ? 'Una defensa promedio' : 'Un cuerpo de lanzadores promedio'}. Espera algo cercano a la proyección.`],
  [/^A strong (defense|pitching staff)\. Your player is more likely to fall short\.$/, (m) => `${m[1] === 'defense' ? 'Una defensa fuerte' : 'Un cuerpo de lanzadores fuerte'}. Es más probable que tu jugador se quede corto.`],
  // formatDate in hubModel: "Nov 13, 2026, 3:00 PM"
  [/^([A-Z][a-z]{2}) (\d{1,2}), (\d{4}), (\d{1,2}):(\d{2}) (AM|PM)$/, (m) => `${m[2]} ${MONTHS_ES[m[1]!] ?? m[1]} ${m[3]}, ${m[4]}:${m[5]} ${m[6] === 'AM' ? 'a. m.' : 'p. m.'}`],
]

export function isSpanish(lang: string | null | undefined): boolean {
  return String(lang ?? '').toLowerCase().startsWith('es')
}

/**
 * The hub's text in `lang`. English (or any language without a table) returns the input unchanged;
 * Spanish returns the translation when this module knows the string, and the English otherwise.
 */
export function hubText(lang: string | null | undefined, text: string, sport?: string | null, opts?: { stat?: boolean }): string {
  if (!isSpanish(lang) || !text) return text
  const family = sportFamily(resolveHubSport(sport))
  const tr: Tr = (s) => hubText(lang, s, sport)
  if (opts?.stat) {
    const stat = STAT_ES_BY_FAMILY[family]?.[text] ?? STAT_ES[text]
    if (stat) return stat
  }
  const own = ES_BY_FAMILY[family]?.[text]
  if (own) return own
  const hit = ES[text]
  if (hit) return hit
  for (const [re, fn] of PATTERNS) {
    const m = re.exec(text)
    if (m) return fn(m, tr)
  }
  return text
}

/**
 * A day in the daily waiver schedule. "Waivers" there is a RUN — «Reclamos» — while the same English
 * word as a section or tab is the free-agent screen, «Agentes libres» (the owner's wording rulings,
 * __tests__/spanish-wording-rulings.test.tsx). So the schedule cell has its own lookup.
 */
export function hubScheduleMode(lang: string | null | undefined, mode: string, sport?: string | null): string {
  if (isSpanish(lang) && mode === 'Waivers') return 'Reclamos'
  return hubText(lang, mode, sport)
}

/** "2026 & 2025" → "2026 y 2025" in Spanish; a range is unchanged. */
export function hubSeasons(lang: string | null | undefined, label: string): string {
  return isSpanish(lang) ? label.replace(' & ', ' y ') : label
}

/** BCP-47 locale for dates in the hub. */
export function hubLocale(lang: string | null | undefined): string {
  return isSpanish(lang) ? 'es-US' : 'en-US'
}

