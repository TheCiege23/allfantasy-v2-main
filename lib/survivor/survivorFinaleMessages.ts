export type SurvivorFinaleMessages = typeof survivorFinaleMessages.en

/** The message for an API refusal code; unknown codes get the generic line. */
export function finaleErrorMessage(m: SurvivorFinaleMessages, code: string | null | undefined): string {
  const key = `errors_${code ?? ''}` as keyof SurvivorFinaleMessages
  const value = m[key]
  return typeof value === 'string' ? value : m.errors_generic
}
