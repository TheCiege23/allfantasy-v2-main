// @vitest-environment node
/**
 * Every colour opacity modifier the code uses (`border-white/8`, `bg-black/72`, `text-white/88` …) must
 * be a step Tailwind will generate. Tailwind 3.4 ships 0, 5, 10 … 100; anything else generates NOTHING,
 * with no warning — `border-white/8` (hundreds of uses) silently fell back to Preflight's light-grey
 * border. Off-scale steps live in `tailwind.config.js` → `theme.extend.opacity`. Use a scale step, or
 * add yours there.
 */
import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'

const ROOT = path.resolve(__dirname, '..', '..')
const DIRS = ['app', 'components', 'lib']
const DEFAULT_SCALE = new Set(Array.from({ length: 21 }, (_, i) => String(i * 5)))
const MODIFIER =
  /\b(?:bg|text|border|border-[trblxy]|ring|ring-offset|divide|outline|from|via|to|fill|stroke|shadow|accent|caret|decoration|placeholder)-(?:white|black|transparent|current|[a-z]+-\d{2,3}|\[#[0-9a-fA-F]{3,8}\])\/(\d+)\b/g

function walk(dir: string, out: string[]) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full, out)
    else if (/\.(tsx?|jsx?)$/.test(entry.name)) out.push(full)
  }
}

describe('Tailwind opacity steps', () => {
  it('every opacity modifier in app/, components/ and lib/ is generated by the Tailwind config', () => {
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    const config = require(path.join(ROOT, 'tailwind.config.js'))
    const extended = new Set(Object.keys(config?.theme?.extend?.opacity ?? {}))
    const files: string[] = []
    for (const d of DIRS) walk(path.join(ROOT, d), files)
    expect(files.length).toBeGreaterThan(500) // the scan really ran over the source tree

    const missing = new Map<string, string>()
    for (const file of files) {
      const text = fs.readFileSync(file, 'utf8')
      for (const m of text.matchAll(MODIFIER)) {
        const step = m[1]!
        if (!DEFAULT_SCALE.has(step) && !extended.has(step) && !missing.has(step)) {
          missing.set(step, `${path.relative(ROOT, file)}: ${m[0]}`)
        }
      }
    }
    expect([...missing.values()], 'add these steps to theme.extend.opacity in tailwind.config.js').toEqual([])
  })
})
