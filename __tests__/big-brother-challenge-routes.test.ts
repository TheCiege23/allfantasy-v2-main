import { beforeEach, describe, expect, it, vi } from 'vitest'
const m = vi.hoisted(() => ({ session: vi.fn(), league: vi.fn(), cycle: vi.fn(), config: vi.fn(), current: vi.fn(), eligible: vi.fn(), automation: vi.fn(), assign: vi.fn(), veto: vi.fn(), transition: vi.fn(), audit: vi.fn() }))
vi.mock('next-auth', () => ({ getServerSession: m.session }))
vi.mock('@/lib/auth', () => ({ authOptions: {} }))
vi.mock('@/lib/prisma', () => ({ prisma: { league: { findUnique: m.league }, bigBrotherCycle: { findUnique: m.cycle } } }))
vi.mock('@/lib/big-brother/BigBrotherLeagueConfig', () => ({ isBigBrotherLeague: vi.fn(async () => true), getBigBrotherConfig: m.config }))
vi.mock('@/lib/big-brother/BigBrotherPhaseStateMachine', () => ({ getCurrentCycleForLeague: m.current, transitionPhase: m.transition }))
vi.mock('@/lib/big-brother/BigBrotherHOHEngine', () => ({ getEligibleHOHRosterIds: m.eligible, assignHOH: m.assign }))
vi.mock('@/lib/big-brother/BigBrotherVetoEngine', () => ({ setVetoWinner: m.veto }))
vi.mock('@/lib/big-brother/BigBrotherAutomationService', () => ({ runAutomation: m.automation }))
vi.mock('@/lib/big-brother/BigBrotherHaveNotPenaltyService', () => ({ applyHaveNotWaiverPenalties: vi.fn(async () => []) }))
vi.mock('@/lib/big-brother/BigBrotherChatAnnouncements', () => ({ announceHOHWinner: vi.fn() }))
vi.mock('@/lib/big-brother/ai/getRosterDisplayNames', () => ({ getRosterDisplayNamesForLeague: vi.fn(async () => ({ r: 'Team R' })) }))
vi.mock('@/lib/big-brother/sport-adapter', () => ({ getVetoChallengeThemeHints: vi.fn() }))
vi.mock('@/lib/big-brother/BigBrotherAuditLog', () => ({ appendBigBrotherAudit: m.audit }))
import { POST as hoh } from '@/app/api/leagues/[leagueId]/big-brother/hoh/route'
import { POST as veto } from '@/app/api/leagues/[leagueId]/big-brother/veto-challenge/route'
const call = (handler: typeof hoh, body = {}) => handler(new Request('https://allfantasy.ai/challenge', { method: 'POST', body: JSON.stringify(body) }) as never, { params: Promise.resolve({ leagueId: 'l' }) })
beforeEach(() => {
  vi.resetAllMocks()
  m.session.mockResolvedValue({ user: { id: 'u' } }); m.league.mockResolvedValue({ userId: 'u' })
  m.config.mockResolvedValue({ configId: 'c', challengeMode: 'deterministic_score' })
  m.eligible.mockResolvedValue(['r', 's']); m.assign.mockResolvedValue({ ok: true }); m.veto.mockResolvedValue({ ok: true })
  m.cycle.mockResolvedValue({ vetoParticipantRosterIds: ['r', 's'], vetoWinnerRosterId: 'r', hohRosterId: 'r', phase: 'NOMINATION_OPEN' })
})
describe.each([['HOH', hoh, 'HOH_OPEN', 'auto_hoh'], ['veto', veto, 'VETO_CHALLENGE_OPEN', 'auto_veto']] as const)('%s commissioner challenge', (_name, handler, phase, action) => {
  beforeEach(() => { m.current.mockResolvedValue({ id: 'cycle', week: 4, phase }) })
  it('requires login and commissioner access', async () => {
    m.session.mockResolvedValue(null); expect((await call(handler)).status).toBe(401)
    m.session.mockResolvedValue({ user: { id: 'other' } }); expect((await call(handler)).status).toBe(403)
    expect(m.automation).not.toHaveBeenCalled()
  })
  it('waits for actual final scores even when client supplies invented scores', async () => {
    m.automation.mockResolvedValue({ ok: true, actionTaken: 'skipped_awaiting_final_scores' })
    const response = await call(handler, { scores: { r: 99999, s: 0 } })
    expect(response.status).toBe(409); expect(await response.json()).toEqual({ error: 'Waiting for finalized scores for every eligible competitor' })
    expect(m.automation).toHaveBeenCalledWith({ leagueId: 'l', action, systemUserId: 'u' })
    expect(m.assign).not.toHaveBeenCalled(); expect(m.veto).not.toHaveBeenCalled(); expect(m.transition).not.toHaveBeenCalled()
  })
  it('returns the shared engine winner after a successful resolution', async () => {
    m.automation.mockResolvedValue({ ok: true, actionTaken: action })
    const response = await call(handler)
    expect(response.status).toBe(200)
    expect(await response.json()).toMatchObject(_name === 'HOH' ? { hohRosterId: 'r' } : { vetoWinnerRosterId: 'r' })
    expect(m.assign).not.toHaveBeenCalled(); expect(m.veto).not.toHaveBeenCalled()
  })
  it('retains an explicit eligible commissioner override and audits it as manual', async () => {
    expect((await call(handler, { winnerRosterId: 'foreign' })).status).toBe(400)
    expect((await call(handler, { winnerRosterId: 'r' })).status).toBe(200)
    expect(m.automation).not.toHaveBeenCalled()
    expect(m.audit.mock.calls[0][3]).toMatchObject(_name === 'HOH' ? { challengeMode: 'manual', winnerId: 'r' } : { mode: 'manual', winnerId: 'r' })
  })
  it('honors a paused league for automatic and manual resolution', async () => {
    m.config.mockResolvedValue({ configId: 'c', weekProgressionPaused: true })
    expect((await call(handler)).status).toBe(409)
    expect((await call(handler, { winnerRosterId: 'r' })).status).toBe(409)
    expect(m.automation).not.toHaveBeenCalled(); expect(m.assign).not.toHaveBeenCalled(); expect(m.veto).not.toHaveBeenCalled()
  })
})
